export const localeByCode = (code: string) => locales.find((locale) => locale.code === code);

export interface Alternate { hreflang: string; href: string; }

/** hreflang set for a page that exists in every language. Must be reciprocal on all versions. */
export function alternatesFor(kind: 'home' | 'courses'): Alternate[] {
  const suffix = kind === 'courses' ? 'courses/' : '';
  return [
    { hreflang: 'en', href: `/${suffix}` },
    ...locales.map((locale) => ({ hreflang: locale.code, href: `/${locale.code}/${suffix}` })),
    { hreflang: 'x-default', href: `/${suffix}` },
  ];
}
